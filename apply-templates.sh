#!/usr/bin/env bash
# Render <version>/<variant>/Dockerfile from the templates. The output is committed.
set -euo pipefail
cd "$(dirname "$0")"

jq -r '.variants | to_entries[] | "\(.key) \(.value.template) \(.value.base)"' versions.json |
while read -r variant template base; do
	jq -r '.versions | to_entries[] | "\(.key) \(.value.sha256)"' versions.json |
	while read -r version sha256; do
		mkdir -p "$version/$variant"
		{
			echo "# DO NOT EDIT: generated by apply-templates.sh from Dockerfile-$template.template"
			echo
			sed -e "s|%%BASE%%|$base|g" -e "s|%%TCL_VERSION%%|$version|g" -e "s|%%TCL_SHA256%%|$sha256|g" \
				"Dockerfile-$template.template"
		} > "$version/$variant/Dockerfile"
	done
done
